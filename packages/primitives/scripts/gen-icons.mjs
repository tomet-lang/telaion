// Generates src/icons.generated.ts from the pinned Lucide sprite.
//
// Every icon becomes its own named export, so a bundler keeps only the icons
// that an application imports. Run with `just icons` after the sprite changes.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const spritePath = resolve(root, "vendor/lucide/sprite.svg");
const outPath = resolve(root, "src/icons.generated.ts");

const sprite = readFileSync(spritePath, "utf8");
const version = /@license (lucide-static v[\w.]+ - \w+)/.exec(sprite)?.[1] ?? "lucide-static";

// "arrow-down-0-1" -> "ArrowDown01"; a leading digit gets an underscore.
function exportName(id) {
  const name = id
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  return /^[0-9]/.test(name) ? `_${name}` : name;
}

const symbolPattern = /<symbol id="([^"]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g;
const seen = new Map();
const lines = [];

for (const [, id, viewBox, inner] of sprite.matchAll(symbolPattern)) {
  if (viewBox !== "0 0 24 24") {
    throw new Error(`icon "${id}" has viewBox "${viewBox}"; the Icon component assumes 0 0 24 24`);
  }
  const name = exportName(id);
  if (seen.has(name)) {
    throw new Error(`icons "${seen.get(name)}" and "${id}" both export "${name}"`);
  }
  seen.set(name, id);
  const body = inner
    .split("\n")
    .map((line) => line.trim())
    .join("")
    .replaceAll(" />", "/>");
  lines.push(`export const ${name}: IconData = { name: ${JSON.stringify(id)}, body: ${JSON.stringify(body)} };`);
}

if (lines.length === 0) {
  throw new Error(`no symbols found in ${spritePath}`);
}

const header = `// Generated by scripts/gen-icons.mjs from vendor/lucide/sprite.svg. Do not edit.
// ${version} (see vendor/lucide/LICENSE)

import type { IconData } from "./icon-data.js";

`;
writeFileSync(outPath, header + lines.join("\n") + "\n");
console.log(`wrote ${lines.length} icons to ${outPath}`);
